import { Invoice, RecurringFrequency } from "../types";
import { generateId, calculateInvoiceTotals } from "./invoiceUtils";

/**
 * Calculates the next due date based on a starting date and recurring frequency.
 */
export function calculateNextDueDate(
  startDateStr: string,
  frequency: RecurringFrequency = "monthly"
): string {
  const date = new Date(startDateStr);
  if (isNaN(date.getTime())) {
    return new Date(Date.now() + 30 * 86400000).toISOString().substring(0, 10);
  }

  const freq = frequency.toLowerCase();

  switch (freq) {
    case "weekly":
      date.setDate(date.getDate() + 7);
      break;
    case "quarterly":
      date.setMonth(date.getMonth() + 3);
      break;
    case "annually":
      date.setFullYear(date.getFullYear() + 1);
      break;
    case "monthly":
    default:
      date.setMonth(date.getMonth() + 1);
      break;
  }

  return date.toISOString().substring(0, 10);
}

/**
 * Checks whether an invoice is recurring and has reached or exceeded its next due date.
 */
export function isInvoiceDueForGeneration(
  invoice: Invoice,
  currentDateStr?: string
): boolean {
  if (!invoice.isRecurring) return false;

  const today = currentDateStr
    ? new Date(currentDateStr).getTime()
    : Date.now();

  const targetDateStr = invoice.nextDueDate || invoice.dueDate;
  if (!targetDateStr) return false;

  const targetDate = new Date(targetDateStr).getTime();
  return targetDate <= today;
}

/**
 * Generates the subsequent recurring invoice for a given recurring invoice.
 */
export function generateNextRecurringInvoice(
  sourceInvoice: Invoice,
  invoiceDate?: string
): Invoice {
  const freq = sourceInvoice.recurringFrequency || "monthly";
  const newDate = invoiceDate || sourceInvoice.nextDueDate || new Date().toISOString().substring(0, 10);
  const nextCycleDue = calculateNextDueDate(newDate, freq);

  // Generate unique incremented invoice number
  const baseNum = sourceInvoice.invoiceNumber.replace(/-R\d+$/, "");
  const cycleMatch = sourceInvoice.invoiceNumber.match(/-R(\d+)$/);
  const cycleCount = cycleMatch ? parseInt(cycleMatch[1], 10) + 1 : 2;
  const newInvoiceNumber = `${baseNum}-R${cycleCount}`;

  // Recalculate totals
  const mathResult = calculateInvoiceTotals(
    sourceInvoice.items,
    sourceInvoice.supplierGstin,
    sourceInvoice.customerGstin
  );

  const cleanNotes = (sourceInvoice.notes || "")
    .replace(/\[Recurring:[^\]]+\]/g, "")
    .trim();

  return {
    id: "inv-" + generateId(),
    invoiceNumber: newInvoiceNumber,
    supplierName: sourceInvoice.supplierName,
    supplierGstin: sourceInvoice.supplierGstin,
    supplierAddress: sourceInvoice.supplierAddress,
    customerName: sourceInvoice.customerName,
    customerGstin: sourceInvoice.customerGstin,
    customerAddress: sourceInvoice.customerAddress,
    date: newDate,
    dueDate: nextCycleDue,
    nextDueDate: calculateNextDueDate(nextCycleDue, freq),
    items: mathResult.items,
    subtotal: mathResult.subtotal,
    cgst: mathResult.cgst,
    sgst: mathResult.sgst,
    igst: mathResult.igst,
    taxAmount: mathResult.taxAmount,
    totalAmount: mathResult.totalAmount,
    status: "unpaid",
    paymentStatus: "due",
    amountPaid: 0,
    balanceDue: mathResult.totalAmount,
    category: sourceInvoice.category || "Sales",
    expenseCategory: sourceInvoice.expenseCategory,
    isRecurring: true,
    recurringFrequency: freq,
    autoGenerateDue: sourceInvoice.autoGenerateDue ?? true,
    lastGeneratedDate: new Date().toISOString().substring(0, 10),
    tags: [
      ...(sourceInvoice.tags || []).filter(t => !t.toLowerCase().includes("cycle")),
      "Recurring",
      `Cycle-${cycleCount}`
    ],
    notes: `${cleanNotes ? cleanNotes + "\n" : ""}[Recurring: ${freq} | Auto-generated from ${sourceInvoice.invoiceNumber} | Flagged as due]`,
    createdAt: new Date().toISOString()
  };
}

/**
 * Scans invoices and flags any overdue or due recurring invoices.
 */
export function flagRecurringInvoicesAsDue(
  invoices: Invoice[]
): { updatedInvoices: Invoice[]; hasChanges: boolean; count: number } {
  let count = 0;
  const today = new Date().toISOString().substring(0, 10);

  const updatedInvoices = invoices.map(inv => {
    if (!inv.isRecurring) return inv;

    const dueDate = inv.dueDate || inv.nextDueDate;
    if (!dueDate) return inv;

    const isPastDue = dueDate < today;
    const isDueToday = dueDate === today;

    if ((isPastDue || isDueToday) && inv.status !== "paid" && inv.paymentStatus !== "overdue" && inv.paymentStatus !== "due") {
      count++;
      const updatedStatus: Invoice['status'] = isPastDue ? "overdue" : "unpaid";
      const updatedPaymentStatus: Invoice['paymentStatus'] = isPastDue ? "overdue" : "due";
      return {
        ...inv,
        status: updatedStatus,
        paymentStatus: updatedPaymentStatus
      };
    }

    return inv;
  });

  return {
    updatedInvoices,
    hasChanges: count > 0,
    count
  };
}
