  subtotal: number;
  cgst: number;
  sgst: number;
  igst: number;
  taxAmount: number;
  totalAmount: number;
  status: 'draft' | 'paid' | 'unpaid' | 'overdue' | 'partially_paid';
  paymentStatus?: 'paid' | 'partially_paid' | 'due' | 'overdue';
